#!/usr/bin/env bash
# Make official linux-x86_64 Android NDK usable on aarch64 host (Ubuntu glibc / Termux both fine).
#
#   bash scripts/make-ndk-host-native.sh [NDK path ]
#
# Background: Google only publishes x86_64-host NDK prebuilt binaries (linux-x86_64 /
# darwin-x86_64 / windows-x86_64). On aarch64 host `toolchains/llvm/prebuilt/
# linux-x86_64/bin/*` all give `Exec format error`. But NDK parts truly independent of host arch:
# sysroot (bionic headers + aarch64 stub libs + crtbegin/crtend) and lib/clang/<ver>
# target-arch runtime below (libclang_rt.builtins-aarch64-android.a, aarch64/libunwind.a)
# — fully usable directly, just need a clang driver that runs on this machine.
#
# Script does two things (modifies NDK in place, idempotent; to restore re-extract NDK zip):
#   1. Replace all prebuilt/<host>/bin/*clang* with shims: read API level from argv[0]
#      (aarch64-linux-android31-clang), then use host clang with --sysroot / --target /
#      compiler-rt builtins;
#   2. Point llvm-{ar,ranlib,strip,objcopy,nm,readelf,...} to host LLVM (same arch, can handle
#      aarch64 ELF), so AGP strip task and cmake also work.
#
# Note: deliberately **does not** use NDK bundled clang headers (lib/clang/<ver>/include) — they
# must bind to same clang version; host clang uses own resource dir for arm_neon.h etc,
# otherwise errors "incompatible constant for this __builtin_neon function".
set -euo pipefail

NDK="${1:-${ANDROID_NDK_HOME:-${ANDROID_NDK_ROOT:-}}}"
if [ -z "$NDK" ] || [ ! -d "$NDK/toolchains/llvm/prebuilt" ]; then
        echo "Usage: bash scripts/make-ndk-host-native.sh <NDK path>" >&2
        echo "(or set ANDROID_NDK_HOME)" >&2
    exit 1
fi
NDK=$(cd "$NDK" && pwd)

case "$(uname -m)" in
    aarch64|arm64) ;;
    *)
                echo "This script only for aarch64 host (current $(uname -m))." >&2
                echo "x86_64 host can use official NDK directly, no shim needed." >&2
        exit 1
        ;;
esac

HOST_PRE=$(ls -d "$NDK"/toolchains/llvm/prebuilt/*/ 2>/dev/null | head -n1)
BIN="${HOST_PRE%/}/bin"
[ -d "$BIN" ] || { echo "Cannot find $BIN" >&2; exit 1; }
sysroot="${HOST_PRE%/}/sysroot"
[ -d "$sysroot/usr/lib/aarch64-linux-android" ] || {
        echo "Cannot find aarch64 sysroot: $sysroot/usr/lib/aarch64-linux-android" >&2
    exit 1
}

CLANG=$(command -v clang || true)
[ -n "$CLANG" ] || { echo "Missing host clang: apt install clang (or pkg install clang)" >&2; exit 1; }
CXX=$(command -v clang++ || echo "$CLANG")
CLANG_MAJOR=$("$CLANG" --version | sed -nE '1s/.*clang version ([0-9]+)\..*/\1/p')
[ -n "$CLANG_MAJOR" ] || { echo "Cannot determine clang version" >&2; exit 1; }

# NDK side only borrows target-arch runtime (builtins / libunwind), version may differ from local clang.
NDK_RT_DIR=$(ls -d "${HOST_PRE%/}"/lib/clang/*/lib/linux 2>/dev/null | tail -n1)
[ -n "$NDK_RT_DIR" ] || { echo "Cannot find lib/clang/*/lib/linux in NDK" >&2; exit 1; }

SHIM="$BIN/ndk-clang-shim.sh"
cat > "$SHIM" <<EOF
#!/bin/sh
# Generated by scripts/make-ndk-host-native.sh. Re-run script after modifying NDK prebuilt dir.
self=\$0
# `readlink -f` is GNU-only; resolve through cd instead, which works in POSIX sh.
case \$self in /*) ;; *) self=\$(pwd)/\$self ;; esac
self=\$(CDPATH= cd -- "\$(dirname -- \"\$self\")" && pwd)/\$(basename -- "\$self")
PRE=\$(dirname "\$(dirname "\$self")")
name=\$(basename "\$0")
case "\$name" in
    *clang++*) cc="$CXX";;
    *)         cc="$CLANG";;
esac
case "\$name" in
    aarch64-linux-android[0-9]*-clang*) ;;
    clang|clang++|*-clang|*-clang++) ;;
    *)
                echo "make-ndk-host-native.sh: only aarch64 target supported (call name: \$name)" >&2
        exit 1
        ;;
esac
api=\$(printf '%s' "\$name" | sed -nE 's/^aarch64-linux-android([0-9]+)-.*/\1/p')
[ -n "\$api" ] || api=31
exec "\$cc" "\$@" \\
  --target=aarch64-linux-android\$api \\
  --sysroot="\$PRE/sysroot" \\
  --rtlib=compiler-rt \\
  -L"$NDK_RT_DIR" \\
  -L"$NDK_RT_DIR/aarch64" \\
  -fuse-ld=lld
EOF
chmod +x "$SHIM"

cd "$BIN"
for f in *clang*; do
    [ "$f" = "ndk-clang-shim.sh" ] && continue
    rm -rf "$f"
    ln -s ndk-clang-shim.sh "$f"
done

# Host LLVM tools (same target arch, can handle aarch64 ELF).
LLVM_BIN=""
for d in "/usr/lib/llvm-$CLANG_MAJOR/bin" "/usr/local/opt/llvm/bin" "$(dirname "$CLANG")"; do
    [ -x "$d/llvm-strip" ] && { LLVM_BIN="$d"; break; }
done
if [ -z "$LLVM_BIN" ]; then
        echo "Warning: cannot find host llvm-strip (apt install llvm-$CLANG_MAJOR)." >&2
        echo "      AGP strip task will fail; debug builds usually unaffected." >&2
else
    for t in llvm-ar llvm-ranlib llvm-strip llvm-objcopy llvm-nm llvm-readelf \
             llvm-objdump llvm-size llvm-addr2line llvm-strings llvm-mc llvm-cxxfilt; do
        [ -x "$LLVM_BIN/$t" ] || continue
        rm -f "$t"
        ln -s "$LLVM_BIN/$t" "$t"
    done
fi

echo "OK: $BIN changed to locally executable shims (host clang $CLANG_MAJOR, NDK runtime $NDK_RT_DIR)"
echo "Tip: if Gradle previously reported aapt2 'Exec format error', see aarch64 aapt2 notes in scripts/build-android-game.sh."
