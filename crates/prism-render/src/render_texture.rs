//! Engine-style RenderTexture (CRT style) — offscreen samplable render target with built-in update schedule config.
//!
//! Resource model of Custom Render Texture:
//!
//! - **Pure resource, no component**: this type is only GPU offscreen image + update config; whether to render
//!   decided by [`RtUpdateMode`], execution by engine's [`crate::rt_scheduler::RenderTextureScheduler`]
//!   unified schedule (each frame iterates registered RTs, triggers one fullscreen blit by config).
//! - **Zero coupling with scene**: content from bound update shader ([`RtShader`]), does not read
//!   any ForwardPass output; any downstream shader can sample it via bindless handle.
//! - **Init and update separated**: [`set_init_shader`] (initial fill) executes before [`set_update_shader`]
//!   (iterative compute), each judged independently.
//!
//! Update modes (corresponding to `CustomRenderTextureUpdateMode`):
//! - [`RtUpdateMode::OnLoad`]: render once on first schedule, then stop (manual `request_update` needed).
//! - [`RtUpdateMode::Realtime`]: auto render each frame; `period` controls interval (once every N frames).
//! - [`RtUpdateMode::OnDemand`]: only render next frame after `request_update()` flag.

use anyhow::Context as _;
use ash::vk;

use crate::bindless::{BindlessTextureTable, TextureHandle};
use crate::buffer::find_memory_type;
use crate::context::VulkanContext;

/// Update mode (`CustomRenderTextureUpdateMode`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum RtUpdateMode {
    /// Render once on load / first schedule, no auto update afterwards.
    #[default]
    OnLoad,
    /// Auto render each frame; `RenderTexture::set_period(n)` sets interval (once every n frames).
    Realtime,
    /// No auto render, only execute once after `request_update()` flag.
    OnDemand,
}

/// Built-in shader for update / init (fullscreen blit).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum RtShader {
    /// 4x4 bit-pattern image: 16-bit random pattern (generated by xorshift in scheduler) expanded per bit into
    /// 16 black-white cells — `rt_render.slang`.
    BitmapPattern,
}

/// CRT resource: offscreen color render target + bindless sample handle + update schedule config.
///
/// Image usage: `COLOR_ATTACHMENT` (blit target) | `SAMPLED` (bindless sampling)
/// | `TRANSFER_SRC` (CPU readback).
pub struct RenderTexture {
    /// Cloned device (destroys Vulkan resources on Drop).
    /// Lifetime convention: RT must be destroyed before `VulkanContext` (scheduler holds RT,
    /// scheduler inside GraphRenderer, GraphRenderer destructed before context).
    device: ash::Device,
    image: vk::Image,
    memory: vk::DeviceMemory,
    view: vk::ImageView,
    extent: vk::Extent2D,
    format: vk::Format,
    /// Bindless SRV slot. `resize` overwrites original slot via `write_srv`, handle stays stable,
    /// shaders / materials already referencing RT need no update.
    /// Note: bindless table is bump allocator, no unregister — after RT destroyed slot
    /// remains occupied (few RTs, acceptable; sampling still holding handle after destroy is use-after-free).
    handle: TextureHandle,

    update_mode: RtUpdateMode,
    /// Update interval for Realtime mode (once every N frames; 0/1 = every frame).
    period: u32,
    /// Update shader.
    update_shader: Option<RtShader>,
    /// Init shader (optional; executes once before update).
    init_shader: Option<RtShader>,

    /// Frame count scheduler already ticked.
    frame_counter: u32,
    /// Whether init already executed.
    initialized: bool,
    /// Pending update flag for OnDemand / manual trigger (cleared after next frame executes).
    pending_update: bool,
    /// xorshift32 state — `BitmapPattern` generates random 16-bit pattern each frame.
    rng_state: u32,
}

impl RenderTexture {
    /// Create offscreen RT and register into bindless table. Default update mode = [`RtUpdateMode::OnLoad`]
    /// (after creation needs `set_update_shader` + register into scheduler to render).
    pub fn new(
        context: &VulkanContext,
        bindless: &mut BindlessTextureTable,
        extent: vk::Extent2D,
        format: vk::Format,
    ) -> anyhow::Result<Self> {
        let device = &context.device;

        let image = unsafe {
            device.create_image(
                &vk::ImageCreateInfo::default()
                    .image_type(vk::ImageType::TYPE_2D)
                    .format(format)
                    .extent(vk::Extent3D {
                        width: extent.width,
                        height: extent.height,
                        depth: 1,
                    })
                    .mip_levels(1)
                    .array_layers(1)
                    .samples(vk::SampleCountFlags::TYPE_1)
                    .tiling(vk::ImageTiling::OPTIMAL)
                    .usage(
                        vk::ImageUsageFlags::COLOR_ATTACHMENT
                            | vk::ImageUsageFlags::SAMPLED
                            | vk::ImageUsageFlags::TRANSFER_SRC,
                    )
                    .sharing_mode(vk::SharingMode::EXCLUSIVE),
                None,
            )
        }
        .context("RenderTexture: create image")?;

        let mem_reqs = unsafe { device.get_image_memory_requirements(image) };
        let mem_type = find_memory_type(
            context,
            mem_reqs.memory_type_bits,
            vk::MemoryPropertyFlags::DEVICE_LOCAL,
        )
        .context("RenderTexture: no device-local memory type")?;
        let memory = unsafe {
            device.allocate_memory(
                &vk::MemoryAllocateInfo::default()
                    .allocation_size(mem_reqs.size)
                    .memory_type_index(mem_type),
                None,
            )
        }
        .context("RenderTexture: allocate memory")?;
        unsafe { device.bind_image_memory(image, memory, 0) }
            .context("RenderTexture: bind image memory")?;

        let view = unsafe {
            device.create_image_view(
                &vk::ImageViewCreateInfo::default()
                    .image(image)
                    .view_type(vk::ImageViewType::TYPE_2D)
                    .format(format)
                    .subresource_range(vk::ImageSubresourceRange {
                        aspect_mask: vk::ImageAspectFlags::COLOR,
                        base_mip_level: 0,
                        level_count: 1,
                        base_array_layer: 0,
                        layer_count: 1,
                    }),
                None,
            )
        }
        .context("RenderTexture: create image view")?;

        let handle = bindless
            .register(view)
            .context("RenderTexture: bindless register")?;

        Ok(Self {
            device: device.clone(),
            image,
            memory,
            view,
            extent,
            format,
            handle,
            update_mode: RtUpdateMode::default(),
            period: 1,
            update_shader: None,
            init_shader: None,
            frame_counter: 0,
            initialized: false,
            pending_update: false,
            rng_state: 0x9E37_79B9,
        })
    }

    /// Set update mode (`CustomRenderTextureUpdateMode`).
    pub fn set_update_mode(&mut self, mode: RtUpdateMode) -> &mut Self {
        self.update_mode = mode;
        self
    }

    pub fn update_mode(&self) -> RtUpdateMode {
        self.update_mode
    }

    /// Update interval for Realtime mode: render once every `period` frames (0 same as 1 = every frame).
    pub fn set_period(&mut self, period: u32) -> &mut Self {
        self.period = period.max(1);
        self
    }

    /// Bind update shader (fullscreen blit executed when scheduler ticks).
    pub fn set_update_shader(&mut self, shader: RtShader) -> &mut Self {
        self.update_shader = Some(shader);
        self
    }

    /// Bind init shader (optional; executes once before update on first schedule).
    pub fn set_init_shader(&mut self, shader: RtShader) -> &mut Self {
        self.init_shader = Some(shader);
        self
    }

    /// Manually flag one pending update (OnDemand / any mode force next frame render once).
    pub fn request_update(&mut self) -> &mut Self {
        self.pending_update = true;
        self
    }

    /// Whether need render this frame (init + update judged separately). Does not modify state.
    pub(crate) fn needs_render(&self) -> bool {
        let update_due = match self.update_mode {
            RtUpdateMode::OnLoad => !self.initialized,
            RtUpdateMode::Realtime => {
                self.period == 0 || self.frame_counter.is_multiple_of(self.period)
            }
            RtUpdateMode::OnDemand => self.pending_update,
        };
        let init_due = !self.initialized && self.init_shader.is_some();
        init_due || update_due
    }

    /// Whether init pending (this frame do init fill first).
    pub(crate) fn needs_init(&self) -> bool {
        !self.initialized && self.init_shader.is_some()
    }

    /// Called after this frame render completes (render frames only): flag init complete, clear pending update flag.
    pub(crate) fn mark_rendered(&mut self) {
        self.initialized = true;
        self.pending_update = false;
    }

    /// Called unconditionally at frame end each frame: advance frame counter (period decision depends on it).
    /// Note: must tick every frame, otherwise with `Realtime + period > 1` counter sticks on
    /// non-multiple, RT will never render again.
    pub(crate) fn tick(&mut self) {
        self.frame_counter = self.frame_counter.wrapping_add(1);
    }

    /// Shader used for this frame render (init takes priority).
    pub(crate) fn active_shader(&self) -> Option<RtShader> {
        if self.needs_init() {
            self.init_shader
        } else {
            self.update_shader
        }
    }

    /// Generate this frame's 4x4 random pattern (for BitmapPattern; xorshift32 high 16 bits).
    pub(crate) fn next_pattern(&mut self) -> u16 {
        let mut x = self.rng_state;
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        self.rng_state = x;
        (x >> 16) as u16
    }

    pub fn image(&self) -> vk::Image {
        self.image
    }

    pub fn view(&self) -> vk::ImageView {
        self.view
    }

    pub fn extent(&self) -> vk::Extent2D {
        self.extent
    }

    pub fn format(&self) -> vk::Format {
        self.format
    }

    /// Bindless sample handle — pass to any shader to sample this RT.
    pub fn texture_handle(&self) -> TextureHandle {
        self.handle
    }

    /// Recreate underlying image at new size. Bindless slot overwritten (`write_srv`),
    /// [`texture_handle`](Self::texture_handle) unchanged — referrers need not notice.
    pub fn resize(
        &mut self,
        context: &VulkanContext,
        bindless: &mut BindlessTextureTable,
        new_extent: vk::Extent2D,
    ) -> anyhow::Result<()> {
        if new_extent.width == 0 || new_extent.height == 0 {
            anyhow::bail!("RenderTexture::resize: zero extent");
        }
        if new_extent == self.extent {
            return Ok(());
        }
        let device = &context.device;

        unsafe {
            device.destroy_image_view(self.view, None);
            device.destroy_image(self.image, None);
            device.free_memory(self.memory, None);
        }

        let image = unsafe {
            device.create_image(
                &vk::ImageCreateInfo::default()
                    .image_type(vk::ImageType::TYPE_2D)
                    .format(self.format)
                    .extent(vk::Extent3D {
                        width: new_extent.width,
                        height: new_extent.height,
                        depth: 1,
                    })
                    .mip_levels(1)
                    .array_layers(1)
                    .samples(vk::SampleCountFlags::TYPE_1)
                    .tiling(vk::ImageTiling::OPTIMAL)
                    .usage(
                        vk::ImageUsageFlags::COLOR_ATTACHMENT
                            | vk::ImageUsageFlags::SAMPLED
                            | vk::ImageUsageFlags::TRANSFER_SRC,
                    )
                    .sharing_mode(vk::SharingMode::EXCLUSIVE),
                None,
            )
        }
        .context("RenderTexture::resize: create image")?;

        let mem_reqs = unsafe { device.get_image_memory_requirements(image) };
        let mem_type = find_memory_type(
            context,
            mem_reqs.memory_type_bits,
            vk::MemoryPropertyFlags::DEVICE_LOCAL,
        )
        .context("RenderTexture::resize: no device-local memory type")?;
        let memory = unsafe {
            device.allocate_memory(
                &vk::MemoryAllocateInfo::default()
                    .allocation_size(mem_reqs.size)
                    .memory_type_index(mem_type),
                None,
            )
        }
        .context("RenderTexture::resize: allocate memory")?;
        unsafe { device.bind_image_memory(image, memory, 0) }
            .context("RenderTexture::resize: bind image memory")?;

        let view = unsafe {
            device.create_image_view(
                &vk::ImageViewCreateInfo::default()
                    .image(image)
                    .view_type(vk::ImageViewType::TYPE_2D)
                    .format(self.format)
                    .subresource_range(vk::ImageSubresourceRange {
                        aspect_mask: vk::ImageAspectFlags::COLOR,
                        base_mip_level: 0,
                        level_count: 1,
                        base_array_layer: 0,
                        layer_count: 1,
                    }),
                None,
            )
        }
        .context("RenderTexture::resize: create image view")?;

        bindless.write_srv(self.handle.0, view);

        self.image = image;
        self.memory = memory;
        self.view = view;
        self.extent = new_extent;
        Ok(())
    }

    /// One submit copies RT image to host-visible buffer and reads back RGBA8 pixels.
    ///
    /// Each call creates temp command pool + staging buffer (simple, no resident resources),
    /// only suitable for low-frequency debug read (e.g. `ReadPixels`).
    pub fn readback(&self, context: &VulkanContext) -> anyhow::Result<Vec<u8>> {
        let device = &context.device;
        let pixel_size = match self.format {
            vk::Format::R8G8B8A8_UNORM | vk::Format::R8G8B8A8_SRGB => 4u64,
            vk::Format::R8_UNORM => 1u64,
            vk::Format::R16G16B16A16_SFLOAT => 8u64,
            other => anyhow::bail!("RenderTexture::readback: unsupported format {other:?}"),
        };
        let buffer_size = self.extent.width as u64 * self.extent.height as u64 * pixel_size;

        let pool_info = vk::CommandPoolCreateInfo::default()
            .flags(vk::CommandPoolCreateFlags::TRANSIENT)
            .queue_family_index(context.graphics_queue_family);
        let pool = unsafe { device.create_command_pool(&pool_info, None) }
            .context("RenderTexture::readback: create pool")?;

        let alloc_info = vk::CommandBufferAllocateInfo::default()
            .command_pool(pool)
            .level(vk::CommandBufferLevel::PRIMARY)
            .command_buffer_count(1);
        let cmd = unsafe { device.allocate_command_buffers(&alloc_info) }
            .context("RenderTexture::readback: allocate cmd")?[0];

        let staging = unsafe {
            device.create_buffer(
                &vk::BufferCreateInfo::default()
                    .size(buffer_size)
                    .usage(vk::BufferUsageFlags::TRANSFER_DST),
                None,
            )
        }
        .context("RenderTexture::readback: create staging buffer")?;
        let reqs = unsafe { device.get_buffer_memory_requirements(staging) };
        let mem_type = find_memory_type(
            context,
            reqs.memory_type_bits,
            vk::MemoryPropertyFlags::HOST_VISIBLE | vk::MemoryPropertyFlags::HOST_COHERENT,
        )
        .context("RenderTexture::readback: no host-visible memory")?;
        let staging_mem = unsafe {
            device.allocate_memory(
                &vk::MemoryAllocateInfo::default()
                    .allocation_size(reqs.size)
                    .memory_type_index(mem_type),
                None,
            )
        }
        .context("RenderTexture::readback: allocate staging memory")?;
        unsafe { device.bind_buffer_memory(staging, staging_mem, 0) }
            .context("RenderTexture::readback: bind staging")?;

        let begin = vk::CommandBufferBeginInfo::default()
            .flags(vk::CommandBufferUsageFlags::ONE_TIME_SUBMIT);
        unsafe { device.begin_command_buffer(cmd, &begin) }
            .context("RenderTexture::readback: begin")?;

        let barrier = vk::ImageMemoryBarrier2::default()
            .old_layout(vk::ImageLayout::UNDEFINED)
            .new_layout(vk::ImageLayout::TRANSFER_SRC_OPTIMAL)
            .src_stage_mask(vk::PipelineStageFlags2::ALL_COMMANDS)
            .dst_stage_mask(vk::PipelineStageFlags2::TRANSFER)
            .src_access_mask(vk::AccessFlags2::MEMORY_READ)
            .dst_access_mask(vk::AccessFlags2::TRANSFER_READ)
            .image(self.image)
            .subresource_range(vk::ImageSubresourceRange {
                aspect_mask: vk::ImageAspectFlags::COLOR,
                base_mip_level: 0,
                level_count: 1,
                base_array_layer: 0,
                layer_count: 1,
            });
        let barriers = [barrier];
        let dep = vk::DependencyInfo::default().image_memory_barriers(&barriers);
        let sync2 = crate::vulkan_compat::LegacySync2 {
            device: &context.device,
        };
        unsafe { sync2.cmd_pipeline_barrier2(cmd, &dep) };

        let copy = vk::BufferImageCopy::default()
            .buffer_offset(0)
            .image_subresource(vk::ImageSubresourceLayers {
                aspect_mask: vk::ImageAspectFlags::COLOR,
                mip_level: 0,
                base_array_layer: 0,
                layer_count: 1,
            })
            .image_extent(vk::Extent3D {
                width: self.extent.width,
                height: self.extent.height,
                depth: 1,
            });
        unsafe {
            device.cmd_copy_image_to_buffer(
                cmd,
                self.image,
                vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                staging,
                &[copy],
            );
        }

        unsafe { device.end_command_buffer(cmd) }.context("RenderTexture::readback: end")?;

        let fence = unsafe { device.create_fence(&vk::FenceCreateInfo::default(), None) }
            .context("RenderTexture::readback: create fence")?;
        let cmd_bufs = [cmd];
        let submit = vk::SubmitInfo::default().command_buffers(&cmd_bufs);
        unsafe { device.queue_submit(context.graphics_queue, &[submit], fence) }
            .context("RenderTexture::readback: submit")?;
        unsafe { device.wait_for_fences(&[fence], true, u64::MAX) }
            .context("RenderTexture::readback: wait")?;

        let data = unsafe {
            let ptr = device
                .map_memory(staging_mem, 0, buffer_size, vk::MemoryMapFlags::empty())
                .context("RenderTexture::readback: map")?;
            let bytes = std::slice::from_raw_parts(ptr.cast::<u8>(), buffer_size as usize);
            bytes.to_vec()
        };

        unsafe {
            device.unmap_memory(staging_mem);
            device.destroy_fence(fence, None);
            device.free_command_buffers(pool, &[cmd]);
            device.destroy_buffer(staging, None);
            device.free_memory(staging_mem, None);
            device.destroy_command_pool(pool, None);
        }

        Ok(data)
    }
}

impl Drop for RenderTexture {
    fn drop(&mut self) {
        if self.image == vk::Image::null() {
            return;
        }
        unsafe {
            self.device.destroy_image_view(self.view, None);
            self.device.destroy_image(self.image, None);
            self.device.free_memory(self.memory, None);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Pure logic test construction: GPU handles all empty (device zero value), only validate update state machine.
    /// Drop skips resource destruction on null image. Device zero value is itself UB construction,
    /// but test never reads it (only state machine fields accessed), explicitly exempted with allow.
    #[expect(
        invalid_value,
        reason = "`MaybeUninit` buffer is initialized before every read"
    )]
    fn test_rt(mode: RtUpdateMode, period: u32) -> RenderTexture {
        RenderTexture {
            device: unsafe { std::mem::MaybeUninit::zeroed().assume_init() },
            image: vk::Image::null(),
            memory: vk::DeviceMemory::null(),
            view: vk::ImageView::null(),
            extent: vk::Extent2D {
                width: 64,
                height: 64,
            },
            format: vk::Format::R8G8B8A8_UNORM,
            handle: TextureHandle(0),
            update_mode: mode,
            period,
            update_shader: Some(RtShader::BitmapPattern),
            init_shader: None,
            frame_counter: 0,
            initialized: false,
            pending_update: false,
            rng_state: 0x9E37_79B9,
        }
    }

    /// Simulate one scheduler frame: judge → render → frame-end advance.
    fn simulate_frame(rt: &mut RenderTexture) -> bool {
        let rendered = rt.needs_render();
        if rendered {
            rt.mark_rendered();
        }
        rt.tick();
        rendered
    }

    #[test]
    fn onload_renders_once_then_stops() {
        let mut rt = test_rt(RtUpdateMode::OnLoad, 0);
        assert!(simulate_frame(&mut rt));
        for _ in 0..4 {
            assert!(!simulate_frame(&mut rt));
        }
    }

    #[test]
    fn realtime_period_zero_renders_every_frame() {
        let mut rt = test_rt(RtUpdateMode::Realtime, 0);
        for _ in 0..8 {
            assert!(simulate_frame(&mut rt));
        }
    }

    #[test]
    fn realtime_period_2_renders_every_other_frame() {
        let mut rt = test_rt(RtUpdateMode::Realtime, 2);
        let rendered: Vec<bool> = (0..8).map(|_| simulate_frame(&mut rt)).collect();
        assert_eq!(
            rendered,
            vec![true, false, true, false, true, false, true, false]
        );
        assert_eq!(rt.frame_counter, 8);
    }

    #[test]
    fn ondemand_requires_request_update() {
        let mut rt = test_rt(RtUpdateMode::OnDemand, 0);
        assert!(!simulate_frame(&mut rt));
        assert!(!simulate_frame(&mut rt));
        rt.request_update();
        assert!(simulate_frame(&mut rt));
        assert!(!simulate_frame(&mut rt));
    }

    #[test]
    fn init_shader_priority_and_active_shader() {
        let mut rt = test_rt(RtUpdateMode::OnLoad, 0);
        assert_eq!(rt.active_shader(), Some(RtShader::BitmapPattern));
        assert!(!rt.needs_init());
        rt.init_shader = Some(RtShader::BitmapPattern);
        assert!(rt.needs_init());
        assert_eq!(rt.active_shader(), Some(RtShader::BitmapPattern));
        rt.mark_rendered();
        assert!(!rt.needs_init());
        assert_eq!(rt.active_shader(), Some(RtShader::BitmapPattern));
    }

    #[test]
    fn shaderless_rt_stays_pending_until_shader_bound() {
        let mut rt = test_rt(RtUpdateMode::OnLoad, 0);
        rt.update_shader = None;
        rt.init_shader = None;
        assert_eq!(rt.active_shader(), None);
        assert!(rt.needs_render());
        rt.tick();
        assert!(rt.needs_render());
        rt.update_shader = Some(RtShader::BitmapPattern);
        assert_eq!(rt.active_shader(), Some(RtShader::BitmapPattern));
        assert!(simulate_frame(&mut rt));
        assert!(!simulate_frame(&mut rt));
    }

    #[test]
    fn xorshift_pattern_deterministic_and_varies() {
        let mut a = test_rt(RtUpdateMode::Realtime, 0);
        let mut b = test_rt(RtUpdateMode::Realtime, 0);
        assert_eq!(a.next_pattern(), b.next_pattern());
        let first = a.next_pattern();
        let second = a.next_pattern();
        assert_ne!(first, second);
    }
}
