//! Lake world: layered parallax background + day/night texture swap.
//!
//! This is **user project** content (level choreography), not an engine capability:
//! `assets/data/lake_layers.json` describes lake texture layer order and parallax factors, this module generates
//! one sprite entity per layer for "current time-of-day", then:
//!
//! - Each frame translates layers by camera position (`pos = base + (cam - origin) * parallax`),
//!   far layers nearly pinned to screen, near layers follow world;
//! - Rotates dawn → day → dusk → night by engine `TimeOfDay` clock: only rewrites
//!   `sprite_path`, asset resolver re-uploads on path change, entities not regenerated.
//!
//! Texture layer list and order in `assets/data/lake_layers.json`; art generated by
//! `scripts/gen_placeholder_sprites.py`, filenames consistent with scene references.
//!
//! State and read / write through [`prism_game_api::GameWorld`] (same as `boat.rs`), so this
//! level logic compiles into static Player and runs as editor-loaded dynamic module unchanged.

use prism_game_api::GameWorld;
use prism_scene::components::{Camera, LocalTransform, SpriteRenderer, TimeOfDay, TimeOfDayPhase};
use serde::Deserialize;

/// Pixels per world unit: 1 pixel = 1 world unit, camera orthographic half height 180 → viewport 360
/// art pixels (640×360 virtual resolution).
const PIXELS_PER_UNIT: f32 = 1.0;
/// z where background layers sit (behind boat and water).
const BG_Z: f32 = -20.0;
/// Half-width of the reflection clip rect.
///
/// The rect only exists to cut the mirror at the water line, so its x range
/// has to cover every camera position; the lake is a few hundred units wide.
const REFLECTION_CLIP_HALF_WIDTH: f32 = 10_000.0;

#[derive(Deserialize)]
struct LayersFile {
    layers: Vec<LayerDef>,
    time_of_day: Vec<String>,
    /// World y of water surface (reflection mirror axis).
    water_line: f32,
    /// Camera position at choreography time; parallax origin.
    camera_origin: [f32; 2],
}

#[derive(Deserialize)]
struct LayerDef {
    slug: String,
    parallax: f32,
    /// World y of this layer bottom edge (pivot at bottom center).
    x: f32,
    y: f32,
    /// Whether to generate a mirror below water (side-view screen reflection).
    #[serde(default)]
    reflect: bool,
    /// Uniform scale (compensates art height vs viewport height), default 1.
    #[serde(default = "unit_scale")]
    scale: f32,
    /// Sort layer; default equals texture layer index (far → near). Explicitly set when foreground layer must cover water.
    #[serde(default)]
    sorting: Option<i32>,
}

/// One texture layer entity.
struct LayerInstance {
    entity: prism_game_api::EntityHandle,
    base: glam::Vec3,
    parallax: f32,
    slug: String,
    /// Mirror entity below water (same layer same parallax, y from water mirror).
    reflection: Option<prism_game_api::EntityHandle>,
}

/// Lake state — **project-private**, held by caller (Player side in ECS resource).
pub struct LakeWorld {
    camera: Option<prism_game_api::EntityHandle>,
    layers: Vec<LayerInstance>,
    tods: Vec<String>,
    current_tod: usize,
    /// Seconds interval for last writing "current time" to save (#984: restart preserves day/night).
    clock_save_timer: f32,
    /// Whether this run already restored time from save.
    clock_restored: bool,
    /// Parallax origin (camera position at choreography).
    camera_origin: glam::Vec2,
    /// Water world y (reflection mirror axis).
    water_line: f32,
}

impl LakeWorld {
    /// Current texture layer count (Play log / smoke test confirms world built).
    pub fn layer_count(&self) -> usize {
        self.layers.len()
    }

    /// Water world y (reflection mirror axis).
    pub fn water_line(&self) -> f32 {
        self.water_line
    }

    fn build(world: &mut GameWorld<'_>) -> Self {
        let camera = world.query::<Camera>().first().copied();

        let (layers_def, tods, camera_origin, water_line) = match load_layers(world) {
            Ok(file) => (
                file.layers,
                file.time_of_day,
                file.camera_origin,
                file.water_line,
            ),
            Err(err) => {
                log::error!("data/lake_layers.json: {err}");
                (Vec::new(), Vec::new(), [0.0, 0.0], 0.0)
            }
        };
        let camera_origin = glam::Vec2::new(camera_origin[0], camera_origin[1]);
        let current_tod = initial_tod(&tods);
        let tod_name = tods.get(current_tod).cloned().unwrap_or_default();

        let mut layers = Vec::new();
        for (order, def) in layers_def.iter().enumerate() {
            let path = layer_path(world, &def.slug, &tod_name);
            let entity = world.spawn();
            let base = glam::Vec3::new(def.x, def.y, BG_Z + order as f32 * 0.01);
            world.set(
                entity,
                LocalTransform {
                    position: base,
                    scale: glam::Vec3::splat(def.scale),
                    ..LocalTransform::default()
                },
            );
            world.set(
                entity,
                SpriteRenderer {
                    sprite_path: path.clone(),
                    pixels_per_unit: PIXELS_PER_UNIT,
                    pivot: [0.5, 0.0],
                    sorting_layer: def.sorting.unwrap_or(order as i32),
                    receive_lights: true,
                    ..SpriteRenderer::default()
                },
            );
            let reflection = def.reflect.then(|| {
                let mirror = world.spawn();
                world.set(
                    mirror,
                    LocalTransform {
                        position: glam::Vec3::new(
                            def.x,
                            reflection_y(def.y, water_line),
                            base.z + 0.005,
                        ),
                        ..LocalTransform::default()
                    },
                );
                world.set(
                    mirror,
                    SpriteRenderer {
                        sprite_path: path.clone(),
                        pixels_per_unit: PIXELS_PER_UNIT,
                        pivot: [0.5, 1.0],
                        flip_y: true,
                        clip_enabled: true,
                        clip_rect: [
                            -REFLECTION_CLIP_HALF_WIDTH,
                            -REFLECTION_CLIP_HALF_WIDTH,
                            REFLECTION_CLIP_HALF_WIDTH,
                            water_line,
                        ],
                        sorting_layer: def.sorting.unwrap_or(order as i32) + 30,
                        color: [0.45, 0.6, 0.85, 0.5],
                        receive_lights: true,
                        ..SpriteRenderer::default()
                    },
                );
                mirror
            });

            layers.push(LayerInstance {
                entity,
                base,
                parallax: def.parallax,
                slug: def.slug.clone(),
                reflection,
            });
        }

        log::info!(
            "lake world: {} layer(s), start time-of-day '{}'",
            layers_def.len(),
            tod_name
        );

        Self {
            camera,
            layers,
            tods,
            current_tod,
            clock_save_timer: 0.0,
            clock_restored: false,
            camera_origin,
            water_line,
        }
    }

    /// Switch time-of-day: only swaps texture path and lets asset system re-resolve.
    fn apply_time_of_day(&self, world: &mut GameWorld<'_>, tod: &str) {
        for layer in &self.layers {
            let path = layer_path(world, &layer.slug, tod);
            for entity in std::iter::once(layer.entity).chain(layer.reflection) {
                if let Some(mut sprite) = world.get::<SpriteRenderer>(entity) {
                    if sprite.sprite_path == path {
                        continue;
                    }
                    sprite.sprite_path = path.clone();
                    world.set(entity, sprite);
                }
            }
        }
    }
}

fn unit_scale() -> f32 {
    1.0
}

/// Y of a reflection whose source bottom edge is at `source_y`.
///
/// The mirror uses its top edge as the pivot, so the source's bottom edge maps
/// onto the mirror's top edge. Everything above the water line is cut by
/// `clip_rect`; do not clamp this value to the line, or the mirror would be
/// parked on the water instead of following the layer's parallax (#1052).
fn reflection_y(source_y: f32, water_line: f32) -> f32 {
    2.0 * water_line - source_y
}

/// Texture layer texture path; when texture missing for that time falls back to `day` (if also missing uses time name,
/// parse failure just does not draw, no crash).
fn layer_path(world: &GameWorld<'_>, slug: &str, tod: &str) -> String {
    let candidate = format!("sprites/bg/{slug}@{tod}.png");
    if world.asset_exists(&candidate) {
        return candidate;
    }
    let fallback = format!("sprites/bg/{slug}@day.png");
    if world.asset_exists(&fallback) {
        return fallback;
    }
    candidate
}

/// Initial time is `day`, if absent first.
fn initial_tod(tods: &[String]) -> usize {
    tods.iter().position(|t| t == "day").unwrap_or(0)
}

fn load_layers(world: &GameWorld<'_>) -> Result<LayersFile, String> {
    let text = world
        .read_asset_text("data/lake_layers.json")
        .map_err(|e| format!("read data/lake_layers.json: {e}"))?;
    serde_json::from_str(&text).map_err(|e| format!("parse lake_layers.json: {e}"))
}

/// Each frame: advance day/night, translate layers.
/// Engine `TimeOfDay` phase → `time_of_day` name in `data/lake_layers.json`.
fn lake_phase(world: &mut GameWorld<'_>) -> Option<&'static str> {
    let clock = world
        .query::<TimeOfDay>()
        .into_iter()
        .find_map(|entity| world.get::<TimeOfDay>(entity))?;
    Some(match clock.phase() {
        TimeOfDayPhase::Dawn => "dawn",
        TimeOfDayPhase::Day => "day",
        TimeOfDayPhase::Dusk => "dusk",
        TimeOfDayPhase::Night => "night",
    })
}

pub fn tick(state: &mut Option<LakeWorld>, world: &mut GameWorld<'_>, dt: f32) {
    if state.is_none() {
        *state = Some(LakeWorld::build(world));
    }
    let Some(current) = state.as_mut() else {
        return;
    };

    if !current.clock_restored {
        current.clock_restored = true;
        if let Some(saved) = world
            .load_data("hours")
            .and_then(|value| value.parse::<f32>().ok())
        {
            if let Some(entity) = world
                .query::<TimeOfDay>()
                .into_iter()
                .find(|entity| world.get::<TimeOfDay>(*entity).is_some())
            {
                let mut clock = world.get::<TimeOfDay>(entity).expect("clock");
                clock.hours = saved.rem_euclid(24.0);
                world.set(entity, clock);
                log::info!("time of day restored: {}", clock.clock_text());
            }
        }
    }

    if !current.tods.is_empty() {
        if let Some(phase) = lake_phase(world) {
            let tod = current
                .tods
                .iter()
                .position(|name| name.eq_ignore_ascii_case(phase))
                .unwrap_or(current.current_tod)
                .min(current.tods.len().saturating_sub(1));
            if tod != current.current_tod {
                current.current_tod = tod;
                let name = current.tods[tod].clone();
                log::info!("time of day -> {name}");
                current.apply_time_of_day(world, &name);
            }
        }
    }

    current.clock_save_timer += dt;
    if current.clock_save_timer >= 2.0 {
        current.clock_save_timer = 0.0;
        if let Some(clock) = world
            .query::<TimeOfDay>()
            .into_iter()
            .find_map(|entity| world.get::<TimeOfDay>(entity))
        {
            let hours = format!("{:.3}", clock.normalized_hours());
            world.save_data("hours", &hours);
        }
    }

    let camera_pos = current
        .camera
        .and_then(|camera| world.get::<LocalTransform>(camera))
        .map(|transform| transform.position)
        .unwrap_or_default();

    for layer in &current.layers {
        let x = layer.base.x + (camera_pos.x - current.camera_origin.x) * layer.parallax;
        let y = layer.base.y + (camera_pos.y - current.camera_origin.y) * layer.parallax;
        if let Some(mut transform) = world.get::<LocalTransform>(layer.entity) {
            transform.position.x = x;
            transform.position.y = y;
            world.set(layer.entity, transform);
        }
        if let Some(mirror) = layer.reflection {
            if let Some(mut transform) = world.get::<LocalTransform>(mirror) {
                transform.position.x = x;
                transform.position.y = reflection_y(y, current.water_line);
                world.set(mirror, transform);
            }
        }
    }
}
